#!/usr/bin/env python3
"""Print the TESTBENCH-LOCAL startup-ramp netlist (DR-0020 Candidate 2) to stdout.

Derived textually from design/sg13cmos5l/netlist/ldo_core_cmos5l.spice (which is
read, never written): the core subckt keeps its name and its six ports, its
`Xamp` reference pin moves from VREF to an internal node VREFR, and the ramp
cell is added inside the subckt (the ramp taps IBIAS, EN and the amplifier's
reference pin, none of which a pure instantiating wrapper can reach). Every
other line of the committed netlist (including the amplifier subckt) is copied
unchanged. Keeping the subckt name means the unchanged startup bench
(`tb_startup_cmos5l.spice.tmpl`, `Xtop ... ldo_core_cmos5l`) picks the wrapper
up through its one `.include` line, with no template edit.

Fails closed: if the committed core no longer has exactly one `Xamp ... VREF`
line and one `.ends` the wrapper is NOT emitted.

Usage: gen_core_with_ramp.py > core_with_ramp.spice
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CORE = os.path.join(HERE, "..", "..", "design", "sg13cmos5l", "netlist",
                    "ldo_core_cmos5l.spice")

# Candidate values, all unvalidated (DR-0020 "Candidate structure and values").
# I_ramp = 2 uA (IBIAS) x (1u/20u)/(5u/2u) = 40 nA; Css ~ 10 pF at ~1.09 fF/um^2
# (design/README.md), so T_ramp = Css*VREF/I_ramp ~ 225 us nominal.
RAMP_BLOCK = """\
* ---- TESTBENCH-LOCAL startup ramp (DR-0020 Candidate 2), not a design cell ----
XMrmp VREFR IBIAS VIN VIN sg13_hv_pmos w=1u l=20u ng=1 m=1
XCss VREFR VSS cap_cmomi w=96e-6 l=96e-6 mmin=1 mmax=4 feed=double subblock=0 m=1 mm_ok=1
XMrinvp RENB EN VIN VIN sg13_hv_pmos w=1u l=1u ng=1 m=1
XMrinvn RENB EN VSS VSS sg13_hv_nmos w=1u l=1u ng=1 m=1
XMrst VREFR RENB VSS VSS sg13_hv_nmos w=1u l=1u ng=1 m=1
Xclmp VREFR VREF CLG VIN VSS IBIAS EN ldo_erramp_cmos5l
XMclp VREFR CLG VSS VSS sg13_hv_nmos w=2u l=1u ng=1 m=1
* ---- end ramp ----
"""

HEADER = """\
* ldo_core_cmos5l (startup-ramp variant) -- TESTBENCH-LOCAL, generated by
* sim/ldo-cmos5l-startup-ramp/gen_core_with_ramp.py from
* design/sg13cmos5l/netlist/ldo_core_cmos5l.spice. NOT a design cell: the core
* on main has no soft start (issue #314, DR-0020 stays Proposed). Do not edit.
"""

# top level, after the subckts: record the ramp node for T_ramp (clause d)
SAVE = ".save v(xtop.vrefr)\n"


def derive(core_text):
    lines = core_text.splitlines()
    xamp = [i for i, ln in enumerate(lines) if re.match(r"^Xamp FB VREF EAOUT ", ln)]
    ends = [i for i, ln in enumerate(lines) if ln.startswith(".ends")]
    if len(xamp) != 1 or not ends:
        raise SystemExit("gen_core_with_ramp: committed core has no unique "
                         "'Xamp FB VREF EAOUT' line / .ends; refusing to emit a wrapper")
    out = list(lines)
    out[xamp[0]] = out[xamp[0]].replace("Xamp FB VREF ", "Xamp FB VREFR ", 1)
    first_ends = ends[0]
    if first_ends < xamp[0]:
        raise SystemExit("gen_core_with_ramp: .ends precedes Xamp; unexpected layout")
    out[first_ends:first_ends] = RAMP_BLOCK.rstrip("\n").split("\n")
    return HEADER + "\n".join(out) + "\n" + SAVE


def main():
    with open(CORE, encoding="utf-8") as f:
        sys.stdout.write(derive(f.read()))


if __name__ == "__main__":
    main()
