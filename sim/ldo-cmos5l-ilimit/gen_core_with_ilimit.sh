#!/usr/bin/env bash
# Print the testbench-local wrapper `ldo_core_ilim_tb` to stdout: the committed
# ldo_core_cmos5l subckt body, unchanged, plus one `Xilim` instance. The core
# netlist on main does NOT instantiate the limiter (integration is deferred to
# #190); the limiter taps the core's internal EAOUT node, which is not a core
# port, so the wrapper is derived textually from the core subckt rather than
# instantiated around it. Same six ports as the core.
# Usage: gen_core_with_ilimit.sh > core_with_ilimit.spice  (run_smoke.sh does this)
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
core="${HERE}/../../design/sg13cmos5l/netlist/ldo_core_cmos5l.spice"
echo "* ldo_core_ilim_tb -- TESTBENCH-LOCAL, generated by gen_core_with_ilimit.sh from"
echo "* design/sg13cmos5l/netlist/ldo_core_cmos5l.spice. Not a design cell: the core"
echo "* itself has no limiter (integration deferred to #190). Do not edit."
awk '
  /^\.subckt ldo_core_cmos5l / && !done { sub(/ldo_core_cmos5l/, "ldo_core_ilim_tb"); inside=1 }
  inside && /^\.ends/ {
    print "Xilim VIN VOUT EAOUT IBIAS EN VSS ldo_ilimit_cmos5l"
    print; inside=0; done=1; next }
  inside { print }
' "${core}"
