#!/usr/bin/env python3
"""Generate the HBT pass-device screening decks (issue #139), deterministically.

Writes, for each device in DEVICES and each bench in BENCHES, one klt-sim
circuit body (`decks/tb_<dev>_<bench>.spice`, no analysis and no `.end`: klt
sim owns those and adds the corner's `.lib` card and `.temp`) and one klt sim
request (`decks/request-<dev>-<bench>.json`).  `--check` regenerates in memory
and fails on any byte of drift against the committed files, so a hand edit of
a generated deck cannot go unnoticed (stdlib only, offline).

Benches
  ibsweep   base-current sweep (log10 Ib/A, -8 .. -2.3 for NPN, -8 .. -0.7 for the PNP) at a set of FIXED
            collector-emitter voltages; each `.meas` finds the base current
            and base voltage at which the collector current hits a target.
            Gives beta vs Ic, quasi-saturation (beta at the dropout Vce vs
            beta at active-region Vce), Early voltage (beta ratio at two
            Vce), and base current against the Iq budget.
  vcesweep  Vce sweep (0.02 .. 1.8 V) at a FIXED base current Ib = Ic/beta_f;
            each `.meas` finds the Vce at which Ic first reaches the target:
            the Vce(sat) / dropout the device needs at that forced beta.
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE / "decks"

# Load points of the ratified dropout row (spec/porting-plan.md 1.4; DR-0007
# row 4 = 50 mA ratified, 100 mA = the stretch load).
LOADS_MA = (50, 100)
# Cell count per load: every cell is held at <= 25 mA, inside the VBIC
# model's stated validity (ic < 0.003*Nx A, Nx <= 10 => 30 mA per Nx=10 cell).
CELLS = {50: 2, 100: 4}
# Fixed collector-emitter voltages for ibsweep (V): the 0.30 V dropout
# differential (Vin 2.10 - Vout 1.80), an active-region 1.0 V, the 1.50 V
# nominal headroom (Vin 3.30 - Vout 1.80) and the 1.83 V Vin_max headroom
# (3.63 - 1.80).  Keys are the deck suffixes.
VCES = {"v030": 0.30, "v100": 1.00, "v150": 1.50, "v183": 1.83}
# beta_forced values for vcesweep (Ib = Ic / beta_f).
BETAS = (1, 10, 20, 50)
# Single-cell beta-vs-Ic ladder (A), at Vce = 1.0 V.
CELL_IC = {"i100u": 100e-6, "i1m": 1e-3, "i10m": 10e-3, "i25m": 25e-3}

# selft=0: the PDK's VBIC subckt defaults to selft=1 (self-heating on); with an
# ideal current-driven base that makes the DC solve thermally run away (NaN in
# the temperature-limiting function) well before the collector-current targets,
# so the screen is ISOTHERMAL (README.md "Self-heating").
# name -> (polarity, X-line template).  Sizing is a SCREENING choice, not a
# layout proposal: Nx=10 is the model's largest valid emitter count; the
# pnpMPA cell is 10 um x 10 um (the symbol's a = w*l, p = 2(w+l)).
DEVICES = {
    "npn13G2": ("npn", "npn13G2 Nx=10 selft=0"),
    "npn13G2l": ("npn", "npn13G2l Nx=10 selft=0"),
    "npn13G2v": ("npn", "npn13G2v Nx=10 selft=0"),
    "pnpMPA": ("pnp", "pnpMPA a=100p p=40u"),
}
HAND_WRITTEN = ("runner-preamble.cir", "hbt-corners.lib")
BENCHES = ("ibsweep", "vcesweep")
PROCESS = ["bcs", "typ", "wcs"]
TEMPS_C = [-40, 27, 125]

# NPN: 10 nA .. 5 mA of base current (beta ~1e3 puts the 100 uA rung of the
# ladder at ~100 nA of Ib; the upper end stays far below thermal/Ic blow-up).
# PNP: up to 200 mA, because the pnpMPA model's bf is ~1.1 (Ib ~ Ic).
IB_SWEEP = {"npn": "Vs -8 -2.3 0.02", "pnp": "Vs -8 -0.7 0.02"}
VCE_SWEEP = "Vsw 0.02 1.8 0.01"


def g(x):
    return f"{x:.6g}"


def header(dev, bench, pol):
    return [
        f"* sg13g2-ldo -- HBT pass-device screening, {dev} ({pol}), bench {bench} (issue #139).",
        "* GENERATED by sim/pass-device-screening-hbt/gen_decks.py -- do not edit;",
        "* edit the generator and re-run it (`gen_decks.py --check` gates drift).",
        "* A klt-sim CIRCUIT BODY: no analysis, no .end; klt sim adds the corner",
        "* .lib card (hbt-corners.lib -> the PDK's cornerHBT.lib), .temp and the analysis.",
        "* Methodology, topology reading and caveats: README.md.",
        '.include "runner-preamble.cir"',
    ]


def xline(name, pol, spec, nodes, m):
    sub, params = spec.split(" ", 1)
    c, b, e = nodes
    if pol == "npn":
        return f"X{name} {c} {b} {e} 0 {sub} {params} m={m}"
    return f"X{name} {c} {b} {e} {sub} {params} m={m}"


def ibsweep(dev, pol, spec):
    """Groups: <load>_<vce> for both loads, plus the single-cell ladder."""
    L = header(dev, "ibsweep", pol)
    L += [
        "* Swept source Vs carries log10(Ib/A); Bibn mirrors Ib as a node voltage so",
        "* `.meas` can FIND it.  Every group is an independent DUT with its own",
        "* fixed-Vce source and its own copy of the base current (Bib_*).",
        "Vs vs 0 dc -3",
        "Bibn ibn 0 V = 10^V(vs)",
    ]
    meas = []
    sgn = -1 if pol == "npn" else 1  # current sign through the collector sense source

    def group(tag, vce, m, targets):
        c, b, e = f"c_{tag}", f"b_{tag}", f"e_{tag}"
        if pol == "npn":
            L.append(f"* group {tag}: Vce={g(vce)} V, m={m}")
            L.append(f"Vc_{tag} {c} 0 dc {g(vce)}")
            L.append(f"Bib_{tag} 0 {b} I = 10^V(vs)")
            L.append(xline(f"q_{tag}", pol, spec, (c, b, "0"), m))
        else:
            L.append(f"* group {tag}: Vec={g(vce)} V, m={m}")
            L.append(f"Ve_{tag} {e} 0 dc {g(vce)}")
            L.append(f"Vc_{tag} {c} 0 dc 0")
            L.append(f"Bib_{tag} {b} 0 I = 10^V(vs)")
            L.append(xline(f"q_{tag}", pol, spec, (c, b, e), m))
        for tname, ic in targets:
            cond = f"i(vc_{tag})={g(sgn * ic)}"
            meas.append((f"ib_{tname}", f".meas dc ib_{tname} FIND v(ibn) WHEN {cond}", "A"))
            meas.append((f"vb_{tname}", f".meas dc vb_{tname} FIND v({b}) WHEN {cond}", "V"))
        # Reachability witness: the largest collector current the group delivered.
        ext = "MIN" if pol == "npn" else "MAX"
        meas.append((f"icext_{tag}", f".meas dc icext_{tag} {ext} i(vc_{tag})", "A"))

    for load in LOADS_MA:
        for vk, vce in VCES.items():
            tag = f"l{load}_{vk}"
            group(tag, vce, CELLS[load], [(tag, load * 1e-3)])
    group("cell", 1.0, 1, [(f"cell_{k}", ic) for k, ic in CELL_IC.items()])
    return "\n".join(L) + "\n", meas


def vcesweep(dev, pol, spec):
    L = header(dev, "vcesweep", pol)
    sweep_node = "cc" if pol == "npn" else "ee"
    L += [
        f"* Swept source Vsw drives the common {'collector' if pol == 'npn' else 'emitter'} rail {sweep_node};",
        "* each group forces Ib = Ic/beta_f through its own current source and senses",
        "* Ic through a 0 V source Vs_*.",
        f"Vsw {sweep_node} 0 dc 1",
    ]
    meas = []
    for load in LOADS_MA:
        for bf in BETAS:
            tag = f"l{load}_b{bf}"
            ic = load * 1e-3
            ib = ic / bf
            m = CELLS[load]
            b = f"b_{tag}"
            if pol == "npn":
                L.append(f"* group {tag}: m={m}, Ib={g(ib)} A (beta_f={bf})")
                L.append(f"Vs_{tag} cc c_{tag} dc 0")
                L.append(f"Ib_{tag} 0 {b} dc {g(ib)}")
                L.append(xline(f"q_{tag}", pol, spec, (f"c_{tag}", b, "0"), m))
            else:
                L.append(f"* group {tag}: m={m}, Ib={g(ib)} A (beta_f={bf})")
                L.append(f"Vs_{tag} c_{tag} 0 dc 0")
                L.append(f"Ib_{tag} {b} 0 dc {g(ib)}")
                L.append(xline(f"q_{tag}", pol, spec, (f"c_{tag}", b, "ee"), m))
            meas.append((f"vce_{tag}", f".meas dc vce_{tag} FIND v({sweep_node}) WHEN i(vs_{tag})={g(ic)}", "V"))
            meas.append((f"vb_{tag}", f".meas dc vb_{tag} FIND v({b}) WHEN i(vs_{tag})={g(ic)}", "V"))
            meas.append((f"icmax_{tag}", f".meas dc icmax_{tag} MAX i(vs_{tag})", "A"))
    return "\n".join(L) + "\n", meas


def request(dev, pol, bench, meas):
    sweep = IB_SWEEP[pol] if bench == "ibsweep" else VCE_SWEEP
    return {
        "netlist": f"tb_{dev}_{bench}.spice",
        "backend": "batch",
        "batch": {"runner_version_check": "warn", "capacity_wait_s": 1800},
        "models": {"lib": "hbt-corners.lib"},
        "analysis": {"kind": "dc", "args": sweep},
        "measurements": [{"name": n, "spice": s, "unit": u} for n, s, u in meas],
        "corners": {"process": PROCESS, "temperature_c": TEMPS_C},
        "options": {"timeout_s": 120, "keep_artifacts": False, "stage_model_inputs": True},
    }


def generate():
    files = {}
    for dev, (pol, spec) in DEVICES.items():
        for bench in BENCHES:
            text, meas = (ibsweep if bench == "ibsweep" else vcesweep)(dev, pol, spec)
            files[f"tb_{dev}_{bench}.spice"] = text
            files[f"request-{dev}-{bench}.json"] = json.dumps(request(dev, pol, bench, meas), indent=2) + "\n"
    return files


def main(argv):
    files = generate()
    if "--check" in argv:
        bad = []
        for name, text in sorted(files.items()):
            p = OUT / name
            if not p.is_file() or p.read_text() != text:
                bad.append(name)
        extra = sorted(p.name for p in OUT.glob("*") if p.is_file() and p.name not in files and p.name not in HAND_WRITTEN)
        if bad or extra:
            print(f"gen_decks.py --check: drift in {bad}; unexpected files {extra}", file=sys.stderr)
            return 1
        print(f"gen_decks.py --check: {len(files)} generated decks match")
        return 0
    OUT.mkdir(exist_ok=True)
    for name, text in files.items():
        (OUT / name).write_text(text)
    print(f"gen_decks.py: wrote {len(files)} files to {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
