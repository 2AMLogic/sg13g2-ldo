def summarise_report(report, prov):
    cs = coords(prov.get("probe", False))
    want = {corner_id(*c): c for c in cs}
    seen = {}
    points = []
    for c in report.get("corners", []):
        cid = c.get("corner_id")
        seen[cid] = seen.get(cid, 0) + 1
        meas = {m["name"]: m for m in c.get("measurements", [])}
        errs = [d for d in c.get("diagnostics", []) if d.get("severity") == "error"]
        coord = want.get(cid)
        p = {
            "corner_id": cid,
            "mos": coord[0] if coord else None,
            "temp_c": coord[1] if coord else None,
            "res_section": f"res_{coord[2]}" if coord else None,
            "corner_status": c.get("status"),
            "error_diagnostics": len(errs),
            "n_steps_reported": len(c.get("steps", [])),
            "steps_all_ok": re_.corner_shape_ok(c, STEP_NAMES, GRADED),
        }
        for n in GRADED:
            p[n] = meas.get(n, {}).get("value")
            p[n + "_status"] = meas.get(n, {}).get("status")
        points.append(p)
    points.sort(key=lambda p: p["corner_id"])

    status_counts = {}
    for p in points:
        status_counts[p["corner_status"]] = status_counts.get(p["corner_status"], 0) + 1
    graded_ok = all(p[n + "_status"] == "pass" for p in points for n in GRADED)
    # Strict "<": the tool's `max` is inclusive, so equality is not credited.
    strictly_below = all(p[n] is not None and p[n] < target_of(n)
                         for p in points for n in GRADED)
    rep_names = [m.get("name") for m in report.get("measurements", [])
                 if m.get("name") in set(GRADED)]
    declared_once = sorted(rep_names) == sorted(GRADED)
    resolved = {n: [p for p in points if p[n] is not None] for n in GRADED}

    def worst(names):
        pool = [(p[n] / target_of(n), p[n], n, p) for p in points for n in names
                if p[n] is not None]
        if not pool:
            return None
        _, v, n, p = max(pool, key=lambda t: (t[0], t[3]["corner_id"]))
        return {"corner_id": p["corner_id"], "mos": p["mos"], "temp_c": p["temp_c"],
                "res_section": p["res_section"], "measurement": n, "value": v,
                "target": target_of(n)}

    w_line, w_load = worst(LINE_GRADED), worst(LOAD_GRADED)
    summ = {
        "record_id": prov["record_id"],
        "probe": bool(prov.get("probe", False)),
        "n_expected": len(cs),
        "n_corners_reported": len(points),
        "coordinates_exactly_once": sorted(seen) == sorted(want) and set(seen.values()) <= {1},
        "envelope_status": report.get("status"),
        "passed": report.get("passed"),
        "failed": report.get("failed"),
        "errored": report.get("errored"),
        "inconclusive": report.get("inconclusive"),
        "corner_status_counts": dict(sorted(status_counts.items())),
        "error_diagnostics_total": sum(p["error_diagnostics"] for p in points),
        "measurements_with_limits": (report.get("coverage") or {}).get("measurements_with_limits"),
        "graded_measurements": list(GRADED),
        "all_graded_measurements_pass": graded_ok,
        "all_graded_strictly_below_target": strictly_below,
        "graded_declarations_exactly_once": declared_once,
        "target_line_mv_per_v": TARGET_LINE_MV_PER_V,
        "target_load_pct": TARGET_LOAD_PCT,
        "line_definition": "1000 * |Vout(3.63 V) - Vout(2.97 V)| / 0.66 at Iload 0, 25 "
                           "and 50 mA, graded as a klt sim derived expr over analysis_steps",
        "load_definition": "100 * |Vout(0 mA) - Vout(50 mA)| / Vout(0 mA) at Vin 2.97, 3.30 "
                           "and 3.63 V, graded as a klt sim derived expr over analysis_steps",
        "qualifications": [
            "ideal 0.90 V reference: reference error is excluded",
            "discrete sampling only: three line loads (0, 25, 50 mA) and three "
            "load-regulation supplies (2.97, 3.30, 3.63 V), not a continuous-window claim",
            "the row's 'inside the accuracy window' coupling to row 2 is NOT "
            "demonstrated by this envelope",
            "schematic level, corner grid only, no Monte Carlo; core WITHOUT the #190 limiter",
        ],
        "solver_convergence_setting_note": "NOT an error bound. The request pins "
            f".options reltol={NGSPICE_OPTIONS['reltol']:g} abstol={NGSPICE_OPTIONS['abstol']:g}; "
            "ngspice's stopping test compares each iterate with the previous one and "
            "bounds nothing about the distance to the exact operating point. No paired "
            "tight-tolerance record exists for row 5: observed solver sensitivity is not claimed",
        "definitive": False,
    }
    if w_line:
        summ["worst_line"] = w_line
    if w_load:
        summ["worst_load"] = w_load
    summ["definitive"] = bool(
        not summ["probe"]
        and summ["n_corners_reported"] == len(cs) == N_EXPECTED
        and summ["coordinates_exactly_once"]
        and summ["envelope_status"] == "pass"
        and summ["passed"] == N_EXPECTED
        and not summ["failed"] and not summ["errored"] and not summ["inconclusive"]
        and summ["error_diagnostics_total"] == 0
        and all(p["steps_all_ok"] for p in points)
        and graded_ok
        and strictly_below
        and declared_once
        and summ["measurements_with_limits"] == len(GRADED)
        and all(len(resolved[n]) == N_EXPECTED for n in GRADED)
    )
    return summ, points


def summary_md(summ, points, prov):
    rid = summ["record_id"]
    L = [f"# Row-5 graded `klt sim` corner-matrix envelope `{rid}`", "",
         "DR-0007 row 5, **Line / load regulation < 5 mV/V; < 1 % over full load** "
         "-- an Open row of the target spec. The verdict below is `klt sim`'s own: "
         "all six graded measurements carry `limits` in `request.json`.", "",
         "Line: " + summ["line_definition"] + ".", "",
         "Load: " + summ["load_definition"] + ".", ""]
    if summ["probe"]:
        L += ["> **PROBE RECORD.** Never cited as row evidence.", ""]
    L += [f"- Corners: {summ['n_corners_reported']}/{summ['n_expected']} reported, "
          f"every coordinate exactly once: {summ['coordinates_exactly_once']}; all eight "
          f"steps ok at every reported corner: {all(p['steps_all_ok'] for p in points)}.",
          f"- Envelope `status`: **{summ['envelope_status']}** (passed {summ['passed']}, "
          f"failed {summ['failed']}, errored {summ['errored']}, inconclusive "
          f"{summ['inconclusive']}).",
          f"- Corner status counts: {summ['corner_status_counts']}; error-severity "
          f"diagnostics: {summ['error_diagnostics_total']}.",
          f"- Graded measurements (`coverage.measurements_with_limits` = "
          f"{summ['measurements_with_limits']}), all tagged `{ROW5_ID}`; all pass: "
          f"{summ['all_graded_measurements_pass']}; all strictly below target: "
          f"{summ['all_graded_strictly_below_target']}."]
    for key, label, unit in (("worst_line", "line", "mV/V"), ("worst_load", "load", "%")):
        if key in summ:
            w = summ[key]
            L.append(f"- Worst {label}: {w['value']:.6g} {unit} (`{w['measurement']}`, "
                     f"`{w['mos']}` / {w['temp_c']} C / `{w['res_section']}`) against "
                     f"{w['target']:g} {unit}.")
    L += [f"- Definitive matrix claim permitted: **{summ['definitive']}**.", "",
          "## Solver convergence setting (not an error bound)", "",
          summ["solver_convergence_setting_note"] + ".", "",
          "## Remaining qualifications", ""]
    L += [f"- {q}" for q in summ["qualifications"]]
    L += ["", "The row stays Open under DR-0007; ratification is `spec/` + "
          "`ratification/` work (#318), never a `signoff/` edit.", "",
          "## Per-corner", "",
          "| corner | status | " + " | ".join(GRADED) + " |",
          "|---|---|" + "---|" * len(GRADED)]
    for p in points:
        cells = [f"`{p['corner_id']}`", str(p["corner_status"])]
        cells += [" " if p[n] is None else f"{p[n]:.6g}" for n in GRADED]
        L.append("| " + " | ".join(cells) + " |")
    L += ["", "## Provenance", ""]
    for k, v in sorted(prov.items()):
        if k == "input_sha256":
            continue
        L.append(f"- {k}: `{json.dumps(v, sort_keys=True)}`" if isinstance(v, (dict, list))
                 else f"- {k}: {v}")
    L += ["", "Input sha256:", ""]
    for k, v in sorted(prov.get("input_sha256", {}).items()):
        L.append(f"- `{k}`: `{v}`")
    L += ["", "Machine summary: `row5-envelope.json`; graded envelope: `report.json`; "
          "request: `request.json`, `tb.spice`, `corners.lib`.", ""]
    return "\n".join(L)


def summary_files(record_dir):
    report = json.load(open(os.path.join(record_dir, "report.json")))
    prov = json.load(open(os.path.join(record_dir, "provenance.json")))
    summ, points = summarise_report(report, prov)
    return {
        "row5-envelope.json": json.dumps({"summary": summ, "points": points},
                                         indent=1, sort_keys=True) + "\n",
        "row5-envelope.md": summary_md(summ, points, prov),
    }, summ


