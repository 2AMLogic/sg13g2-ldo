#!/usr/bin/env python3
"""Graded `klt sim` corner-matrix envelope for DR-0007 row 5, line / load
regulation (issue #319, child of #316).

Row 5 ("Line / load regulation  < 5 mV/V; < 1 % over full load, inside the
accuracy window") was measured only as OFFLINE informational summaries from
discrete loads and supplies, with no `klt sim` envelope carrying `spec_row`.
This bench grades it the same way `row7_envelope.py` grades Iq:

  * eight `analysis_steps[]` operating points per corner, each setting BOTH
    Vin and Iload: Vin 2.97 / 3.63 V at Iload 0 / 25 / 50 mA, and Vin 3.30 V
    at Iload 0 / 50 mA.  The four outer-supply, load-extreme points serve both
    calculations.  Each step reports the raw output voltage `vout_v`
    (ungraded, untagged);
  * the six graded figures are derived `expr` measurements over those step
    results, with the row limit declared INSIDE the request and
    `spec_row: dr0007-row5-line-load-regulation`:

        line_<load>_mvpv = 1000 * abs(Vout_hi - Vout_lo) / (3.63 - 2.97)
        load_<vin>_pct   = 100 * abs(Vout_0mA - Vout_50mA) / Vout_0mA

    so the per-corner and whole-matrix verdict is `klt sim`'s own.  This repo
    never computes a verdict in Python.

Strictness: DR-0007 row 5 says "< 5 mV/V" and "< 1 %".  The pinned grader's
`max` is inclusive (a value exactly at the limit grades `pass`), so the tool's
reported status is preserved verbatim while strict-target credit is withheld
at equality: `all_graded_strictly_below_target` is False and the record is not
`definitive`.

Solver tolerances are pinned in the request (`reltol=1e-9 abstol=1e-15`, the
row-7 setting that resolves the whole grid) because the line figures are
differences of ~1.8 V outputs of ~0.1 mV.  That is a CONVERGENCE SETTING,
not an error bound (ngspice's stopping test compares successive iterates);
no paired tight-tolerance record exists for row 5, so observed solver
sensitivity is NOT claimed.

Qualifications every record's summary states: ideal 0.90 V reference, discrete
sampling only (three line loads, three load-regulation supplies; not a
continuous-window claim), and the row's "inside the accuracy window"
coupling to row 2 is NOT demonstrated by this envelope.

The row stays Open (ratification is #318, never a `signoff/` edit).

    row5_envelope.py submit            # mint a record on the EDA batch fleet
    row5_envelope.py submit --probe    # 2 corners (never cited)
    row5_envelope.py submit --dry-run  # build and validate the request dir
    row5_envelope.py check             # offline, stdlib-only (CI)
    row5_envelope.py summarise <id>    # rewrite that record's summary files

`check` binds BOTH selections this record set carries: the item-8
characterization selection (sim/characterization/selection.json, kept fresh)
and the signoff manifest's item-5 row5-envelope member -- when #318's
citation lands it must name a committed, definitive, non-probe record whose
tb.spice hashes to the manifest's content_hash and whose recorded inputs
are fresh (the shared row4 contract, row_envelope.cited_item5_record #358;
a probe record's tb.spice is byte-identical to the full matrix's, so the
grader cannot make this distinction itself).  While item 5 has no row-5
member the check passes with the citation unresolved.

Append-only; SPICE never runs locally here (the grid goes to the fleet).
"""
import argparse
import json
import os
import sys

import row_envelope as re_

HERE = re_.HERE
REPO = re_.REPO
TEMPLATE = "sim/ldo-cmos5l-pvt-sweep/testbench/tb_row5_envelope_cmos5l.spice.tmpl"
DESIGN_NETLIST = "design/sg13cmos5l/netlist/ldo_core_cmos5l.spice"
ROOT = os.path.join(HERE, "row5-envelope")

# (name, volts); (name, amps)
VIN_LO = ("v2v97", 2.97)
VIN_MID = ("v3v30", 3.30)
VIN_HI = ("v3v63", 3.63)
LINE_LOADS = [("i0", 0.0), ("i25m", 0.025), ("i50m", 0.050)]
LOAD_LO = ("i0", 0.0)
LOAD_HI = ("i50m", 0.050)
LOAD_VINS = [VIN_LO, VIN_MID, VIN_HI]
VIN_SPAN_V = 3.63 - 2.97

TARGET_LINE_MV_PER_V = 5.0
TARGET_LOAD_PCT = 1.0
ROW5_ID = "dr0007-row5-line-load-regulation"

NGSPICE_OPTIONS = {"reltol": 1e-9, "abstol": 1e-15}
NGSPICE_INIT = ["set numdgt=12"]

MOS = re_.MOS
RES = re_.RES
CAP = re_.CAP
TEMPS = re_.TEMPS
N_EXPECTED = re_.N_EXPECTED
PROBE_COORDS = re_.PROBE_COORDS
PDK = re_.PDK
PDK_PIN = re_.PDK_PIN
Error = re_.Error

INPUTS = [TEMPLATE, DESIGN_NETLIST,
          "design/sg13cmos5l/netlist/ldo_erramp_cmos5l.spice",
          "sim/tools/render_deck.py"]

# Byte-critical: names THIS driver (see row_envelope.py's header).
HEADER_LINES = [
    "* generated by sim/ldo-cmos5l-pvt-sweep/row5_envelope.py:",
]


def _operating_points():
    pts = [(VIN_LO, ln) for ln in LINE_LOADS] + [(VIN_HI, ln) for ln in LINE_LOADS]
    pts.insert(3, (VIN_MID, LOAD_LO))
    pts.insert(4, (VIN_MID, LOAD_HI))
    return pts


STEP_NAMES = sorted(f"{vn}_{ln}" for (vn, _), (ln, _) in _operating_points())
LINE_GRADED = [f"line_{ln}_mvpv" for ln, _ in LINE_LOADS]
LOAD_GRADED = [f"load_{vn}_pct" for vn, _ in LOAD_VINS]
GRADED = LINE_GRADED + LOAD_GRADED

coords = re_.coords
section_of = re_.section_of
corner_id = re_.corner_id
sha256_file = re_.sha256_file
write_or_check = re_.write_or_check


def records(root=None):
    return re_.records(root or ROOT)


def analysis_steps():
    """Eight named operating points; each step ALTERs both sources so the
    cumulative-alter semantics land every step at exactly its own bias."""
    steps = []
    for (vn, vv), (ln, lv) in _operating_points():
        steps.append({
            "name": f"{vn}_{ln}",
            "analysis": {"kind": "op", "args": ""},
            "alter": {"Vin": vv, "Iload": lv},
            "measurements": [
                # Reported, deliberately ungraded and untagged.
                {"name": "vout_v", "expr": "v(vout)", "unit": "V"},
            ],
        })
    return steps


def measurements():
    """Six graded figures: derived exprs over the step results, each with the
    row target as `limits` and the row id as `spec_row`."""
    out = []
    hi, lo = VIN_HI[0], VIN_LO[0]
    for ln, _ in LINE_LOADS:
        out.append({
            "name": f"line_{ln}_mvpv",
            "expr": f"1000 * abs({hi}_{ln}.vout_v - {lo}_{ln}.vout_v) / {VIN_SPAN_V:.2f}",
            "unit": "mV/V",
            "limits": {"max": TARGET_LINE_MV_PER_V},
            "spec_row": ROW5_ID,
        })
    z, f = LOAD_LO[0], LOAD_HI[0]
    for vn, _ in LOAD_VINS:
        out.append({
            "name": f"load_{vn}_pct",
            "expr": f"100 * abs({vn}_{z}.vout_v - {vn}_{f}.vout_v) / {vn}_{z}.vout_v",
            "unit": "%",
            "limits": {"max": TARGET_LOAD_PCT},
            "spec_row": ROW5_ID,
        })
    return out


def target_of(name):
    return TARGET_LINE_MV_PER_V if name in LINE_GRADED else TARGET_LOAD_PCT


def request_obj(osdi_dir, cs):
    return re_.request_skeleton(
        cs, "analysis_steps", analysis_steps(), measurements(), osdi_dir,
        extra_options={"ngspice_options": dict(NGSPICE_OPTIONS),
                       "ngspice_init": list(NGSPICE_INIT)},
        timeout_s=900)


def request_files(subs, cs, template_text):
    return re_.request_files(subs, cs, template_text, HEADER_LINES, request_obj)


