def echoed_options_match(report, request):
    asked = (request.get("options") or {}).get("ngspice_options")
    echoed = (report.get("environment") or {}).get("ngspice_options")
    return asked is not None and echoed == asked


def cmd_submit(a):
    def prov_extra(rid, probe):
        return {
            "spec_row": "DR-0007 row 5 (line / load regulation) -- Open; this "
                        "envelope does not ratify it",
            "measurement_definition": "line and load regulation graded as klt sim "
                                      "derived expr measurements over analysis_steps, "
                                      "never computed by repo Python",
            "solver_options": dict(NGSPICE_OPTIONS),
            "input_sha256": {p: sha256_file(os.path.join(REPO, p)) for p in INPUTS},
        }
    return re_.submit_record(
        a, slug="row5", root=ROOT, template_rel=TEMPLATE,
        design_netlist_rel=DESIGN_NETLIST, header_lines=HEADER_LINES,
        request_files_fn=request_files, summary_files_fn=summary_files,
        invocation_fmt="python3 sim/ldo-cmos5l-pvt-sweep/row5_envelope.py submit{probe}",
        prov_extra=prov_extra)


def cmd_summarise(a):
    record_dir = os.path.join(ROOT, a.record_id)
    if not os.path.isdir(record_dir):
        raise Error(f"no such record: {record_dir}")
    files, summ = summary_files(record_dir)
    bad = write_or_check(record_dir, files, check=a.check)
    if bad:
        raise Error("summary files stale or missing: " + ", ".join(bad))
    print(json.dumps(summ, indent=1, sort_keys=True))
    return 0


def check_record(rid, problems):
    record_dir = os.path.join(ROOT, rid)
    if not os.path.exists(os.path.join(record_dir, "provenance.json")):
        problems.append(f"{rid}: no provenance.json")
        return None
    summ, prov = re_.check_request_and_summary(
        record_dir, rid, problems, slug="row5", request_files_fn=request_files,
        template_rel=TEMPLATE, summary_files_fn=summary_files)
    try:
        rep = json.load(open(os.path.join(record_dir, "report.json")))
        req = json.load(open(os.path.join(record_dir, "request.json")))
    except (OSError, ValueError) as exc:
        problems.append(f"{rid}: cannot compare echoed solver options: {exc}")
    else:
        if not echoed_options_match(rep, req):
            problems.append(f"{rid}: report.json environment.ngspice_options != "
                            "request.json options.ngspice_options")
    re_.check_hash_pins(record_dir, rid, problems, slug="row5",
                        tail=f"row5-envelope/{rid}/tb.spice")
    re_.check_declared_gates(record_dir, rid, problems,
                             measurements_fn=measurements, graded=GRADED,
                             row_id=ROW5_ID, slug="row5")
    return summ


def selected_record():
    """The record id selection.json cites for row 5 (None: no record cited)."""
    sel = json.load(open(os.path.join(REPO, "sim", "characterization", "selection.json")))
    return (sel.get("row5_envelope_evidence") or {}).get("id")


def cited_record():
    """(record_id, pinned content_hash) from signoff/sg13g2-ldo.json item 5's
    row5-envelope member, or (None, None) while item 5 cites no row-5 record
    -- the citation itself is #318's edit, not this driver's, and `check`
    passes with item 5 unresolved both before and after it lands. Sharing
    the row-4 contract (row_envelope.cited_item5_record, #358) closes the
    hole that a probe record -- whose tb.spice is byte-identical to the full
    matrix's -- graded identically to the definitive one."""
    return re_.cited_item5_record(REPO, ROOT, ROW5_ID, "row5")


def stale_inputs(rid):
    return re_.stale_inputs(REPO, ROOT, rid, INPUTS)


def cmd_check(a):
    problems = []
    rids = records(ROOT)
    summaries = {rid: check_record(rid, problems) for rid in rids}
    selected = selected_record()
    if selected is not None:
        if selected not in summaries:
            problems.append(f"selection.json cites row-5 record {selected}, "
                            "which is not committed")
        else:
            problems += stale_inputs(selected)
    cited = re_.check_item5_citation(REPO, ROOT, ROW5_ID, "row5", summaries,
                                     problems, stale_inputs)
    for p in problems:
        print("row5_envelope: " + p, file=sys.stderr)
    if problems:
        return 1
    n_def = sum(1 for s in summaries.values() if s and s["definitive"])
    print(f"row5_envelope: OK -- {len(rids)} record(s) reproduce and self-verify "
          f"({n_def} definitive). The row stays Open."
          + (f"; signoff item 5 cites {cited}" if cited else ""))
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sp = ap.add_subparsers(dest="cmd", required=True)
    s = sp.add_parser("submit", help="mint a new record on the EDA batch fleet")
    s.add_argument("--probe", action="store_true",
                   help=f"{len(PROBE_COORDS)} coordinates only; never citable")
    s.add_argument("--dry-run", action="store_true",
                   help="build and validate the request without submitting")
    s.set_defaults(fn=cmd_submit)
    c = sp.add_parser("check", help="offline: every committed record reproduces (CI)")
    c.set_defaults(fn=cmd_check)
    m = sp.add_parser("summarise", help="rewrite one record's summary files")
    m.add_argument("record_id")
    m.add_argument("--check", action="store_true")
    m.set_defaults(fn=cmd_summarise)
    a = ap.parse_args()
    try:
        return a.fn(a)
    except Error as exc:
        print(f"row5_envelope: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
