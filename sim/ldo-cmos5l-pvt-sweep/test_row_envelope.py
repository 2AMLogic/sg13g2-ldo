#!/usr/bin/env python3
"""Contract tests for row_envelope.py, the shared row-envelope machinery
(issue #317). stdlib only, offline.

The contract this file pins is the one the refactor onto a shared module
could have silently broken (the Hermit note on issue #317): the first line of
every corners.lib names the DRIVER that generated it, the fleet report pins
those bytes, and both drivers' request/summary bytes must keep reproducing
from one shared implementation.  Everything else here pins the shared
skeleton's canonical shape, which is itself committed bytes (json.dumps
preserves insertion order).
"""
import json
import os
import sys
import shutil
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)
import row_envelope as re_  # noqa: E402
import row4_envelope as r4  # noqa: E402
import row7_envelope as r7  # noqa: E402

SUBS = {"design_netlist_include": "../x.spice", "pdk_models_dir": "/m",
        "osdi_dir": "/o"}
TMPL = "body @@DESIGN_NETLIST@@\n"


class HeaderBytes(unittest.TestCase):
    """corners.lib's first line names the driver; those bytes are evidence."""

    def test_row4_header_names_row4_driver(self):
        lib = re_.corners_lib_text("/m", re_.coords(), r4.HEADER_LINES)
        self.assertTrue(lib.startswith(
            "* generated by sim/ldo-cmos5l-pvt-sweep/row4_envelope.py:\n"),
            lib.splitlines()[0])

    def test_row7_header_names_row7_driver(self):
        lib = re_.corners_lib_text("/m", re_.coords(), r7.HEADER_LINES)
        self.assertTrue(lib.startswith(
            "* generated by sim/ldo-cmos5l-pvt-sweep/row7_envelope.py:\n"),
            lib.splitlines()[0])

    def test_the_renderer_refuses_a_header_without_a_driver_name(self):
        with self.assertRaises(re_.Error):
            re_.corners_lib_text("/m", re_.coords(),
                                 ["* generated by somebody else:"])
        with self.assertRaises(re_.Error):
            re_.corners_lib_text("/m", re_.coords(), [])

    def test_one_grid_one_spelling_across_drivers(self):
        self.assertIs(r4.coords, r7.coords)
        self.assertIs(r4.section_of, r7.section_of)
        self.assertIs(r4.corner_id, r7.corner_id)
        self.assertEqual(r4.MOS, r7.MOS)
        self.assertEqual(r4.ROOT.rsplit("-", 1)[-1], "envelope")
        self.assertEqual(r7.ROOT.rsplit("-", 1)[-1], "envelope")
        self.assertNotEqual(r4.ROOT, r7.ROOT)

    def test_row4_request_bytes_are_driver_local(self):
        # The two drivers' request dirs differ ONLY in their row-specific
        # halves: the shared renderer must not leak one driver's identity into
        # the other's files.
        a4 = r4.request_files(SUBS, re_.coords(), TMPL)
        a7 = r7.request_files(SUBS, re_.coords(), TMPL)
        self.assertEqual(a4["tb.spice"], a7["tb.spice"])
        self.assertNotEqual(a4["corners.lib"], a7["corners.lib"])
        self.assertIn("row4_envelope.py", a4["corners.lib"])
        self.assertNotIn("row4_envelope.py", a7["corners.lib"])
        self.assertNotEqual(a4["request.json"], a7["request.json"])


class SkeletonShape(unittest.TestCase):
    def test_canonical_key_order_is_the_committed_order(self):
        req = re_.request_skeleton(re_.coords(), "analysis",
                                   {"kind": "dc", "args": "Vin 1 2 1"},
                                   [{"name": "m", "spice": ".meas dc m "
                                    "FIND v(vout) AT=2"}], "/o")
        self.assertEqual(list(req),
                         ["netlist", "backend", "batch", "models", "analysis",
                          "measurements", "corners", "options"])
        self.assertEqual(list(req["options"]),
                         ["timeout_s", "keep_artifacts", "waveforms",
                          "stage_model_inputs", "osdi_preload"])
        self.assertEqual(req["batch"],
                         {"runner_version_check": "warn", "capacity_wait_s": 600})

    def test_probe_exclude_comes_last_and_full_matrix_has_none(self):
        full = re_.request_skeleton(re_.coords(probe=True), "analysis",
                                    {"kind": "op", "args": ""}, [], "/o")
        self.assertEqual(list(full)[-1], "exclude")
        self.assertEqual(len(full["exclude"]), 2)
        none = re_.request_skeleton(re_.coords(), "analysis",
                                    {"kind": "op", "args": ""}, [], "/o")
        self.assertNotIn("exclude", none)

    def test_row4_request_obj_is_the_skeleton_with_row4_halves(self):
        self.assertEqual(r4.request_obj("/o", re_.coords()),
                         re_.request_skeleton(re_.coords(), "analysis",
                                              {"kind": "dc", "args": r4.VIN_AXIS},
                                              r4.measurements(), "/o"))

    def test_row7_request_obj_is_the_skeleton_with_row7_halves(self):
        self.assertEqual(
            r7.request_obj("/o", re_.coords()),
            re_.request_skeleton(
                re_.coords(), "analysis_steps", r7.analysis_steps(),
                r7.measurements(), "/o",
                extra_options={"ngspice_options": dict(r7.NGSPICE_OPTIONS),
                               "ngspice_init": list(r7.NGSPICE_INIT)},
                timeout_s=600))


class GateChecks(unittest.TestCase):
    """The shared declared-gate check catches a dropped tag or relaxed limit
    in a committed record's request, for either driver's shape."""

    def record_dir(self, driver):
        tmp = tempfile.mkdtemp(prefix="row-envelope-gate-test.")
        self.addCleanup(shutil.rmtree, tmp, True)
        files = driver.request_files(SUBS, re_.coords(), TMPL)
        for name, text in files.items():
            with open(os.path.join(tmp, name), "w") as f:
                f.write(text)
        with open(os.path.join(tmp, "report.json"), "w") as f:
            json.dump({"provenance": {"input": {}}, "netlist": "tb.spice",
                       "environment": {}, "measurements": [], "corners": []}, f)
        return tmp

    def test_relaxed_limit_in_the_request_is_caught(self):
        for driver, slug in ((r4, "row4"), (r7, "row7")):
            with self.subTest(driver=slug):
                tmp = self.record_dir(driver)
                path = os.path.join(tmp, "request.json")
                req = json.load(open(path))
                for m in req["measurements"]:
                    if m.get("limits"):
                        m["limits"] = {"max": 9.0}
                json.dump(req, open(path, "w"), indent=1)
                problems = []
                re_.check_declared_gates(tmp, "rid", problems,
                                         measurements_fn=driver.measurements,
                                         graded=driver.GRADED,
                                         row_id=(r4.ROW4_ID if slug == "row4"
                                                 else r7.ROW7_ID),
                                         slug=slug)
                self.assertTrue(any("limits" in p for p in problems), problems)

    def test_dropped_spec_row_tag_is_caught(self):
        tmp = self.record_dir(r7)
        path = os.path.join(tmp, "request.json")
        req = json.load(open(path))
        req["measurements"][0].pop("spec_row")
        json.dump(req, open(path, "w"), indent=1)
        problems = []
        re_.check_declared_gates(tmp, "rid", problems,
                                 measurements_fn=r7.measurements,
                                 graded=r7.GRADED, row_id=r7.ROW7_ID, slug="row7")
        self.assertTrue(any("spec_row" in p for p in problems), problems)

    def test_ungraded_measurement_claiming_a_row_is_caught(self):
        # The step supply currents stay untagged; a tag smuggled onto one
        # would claim row coverage for a quantity that grades nothing.
        tmp = self.record_dir(r7)
        rep = json.load(open(os.path.join(tmp, "report.json")))
        rep["measurements"] = [
            {"name": "v3v30_i0.isup_a", "limits": None, "spec_row": r7.ROW7_ID}]
        json.dump(rep, open(os.path.join(tmp, "report.json"), "w"))
        problems = []
        re_.check_declared_gates(tmp, "rid", problems,
                                 measurements_fn=r7.measurements,
                                 graded=r7.GRADED, row_id=r7.ROW7_ID, slug="row7")
        self.assertTrue(any("claims spec_row" in p for p in problems), problems)





if __name__ == "__main__":
    unittest.main()
