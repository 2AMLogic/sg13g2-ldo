#!/usr/bin/env python3
"""Contract tests for row_envelope.py, the shared row-envelope machinery
(issue #317). stdlib only, offline.

The contract this file pins is the one the refactor onto a shared module
could have silently broken (the Hermit note on issue #317): the first line of
every corners.lib names the DRIVER that generated it, the fleet report pins
those bytes, and both drivers' request/summary bytes must keep reproducing
from one shared implementation.  Everything else here pins the shared
skeleton's canonical shape, which is itself committed bytes (json.dumps
preserves insertion order).
"""
import json
import os
import sys
import shutil
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)
import row_envelope as re_  # noqa: E402
import row4_envelope as r4  # noqa: E402
import row5_envelope as r5  # noqa: E402
import row7_envelope as r7  # noqa: E402

SUBS = {"design_netlist_include": "../x.spice", "pdk_models_dir": "/m",
        "osdi_dir": "/o"}
TMPL = "body @@DESIGN_NETLIST@@\n"


class HeaderBytes(unittest.TestCase):
    """corners.lib's first line names the driver; those bytes are evidence."""

    def test_row4_header_names_row4_driver(self):
        lib = re_.corners_lib_text("/m", re_.coords(), r4.HEADER_LINES)
        self.assertTrue(lib.startswith(
            "* generated by sim/ldo-cmos5l-pvt-sweep/row4_envelope.py:\n"),
            lib.splitlines()[0])

    def test_row7_header_names_row7_driver(self):
        lib = re_.corners_lib_text("/m", re_.coords(), r7.HEADER_LINES)
        self.assertTrue(lib.startswith(
            "* generated by sim/ldo-cmos5l-pvt-sweep/row7_envelope.py:\n"),
            lib.splitlines()[0])

    def test_the_renderer_refuses_a_header_without_a_driver_name(self):
        with self.assertRaises(re_.Error):
            re_.corners_lib_text("/m", re_.coords(),
                                 ["* generated by somebody else:"])
        with self.assertRaises(re_.Error):
            re_.corners_lib_text("/m", re_.coords(), [])

    def test_one_grid_one_spelling_across_drivers(self):
        self.assertIs(r4.coords, r7.coords)
        self.assertIs(r4.section_of, r7.section_of)
        self.assertIs(r4.corner_id, r7.corner_id)
        self.assertEqual(r4.MOS, r7.MOS)
        self.assertEqual(r4.ROOT.rsplit("-", 1)[-1], "envelope")
        self.assertEqual(r7.ROOT.rsplit("-", 1)[-1], "envelope")
        self.assertNotEqual(r4.ROOT, r7.ROOT)

    def test_row4_request_bytes_are_driver_local(self):
        # The two drivers' request dirs differ ONLY in their row-specific
        # halves: the shared renderer must not leak one driver's identity into
        # the other's files.
        a4 = r4.request_files(SUBS, re_.coords(), TMPL)
        a7 = r7.request_files(SUBS, re_.coords(), TMPL)
        self.assertEqual(a4["tb.spice"], a7["tb.spice"])
        self.assertNotEqual(a4["corners.lib"], a7["corners.lib"])
        self.assertIn("row4_envelope.py", a4["corners.lib"])
        self.assertNotIn("row4_envelope.py", a7["corners.lib"])
        self.assertNotEqual(a4["request.json"], a7["request.json"])


class SkeletonShape(unittest.TestCase):
    def test_canonical_key_order_is_the_committed_order(self):
        req = re_.request_skeleton(re_.coords(), "analysis",
                                   {"kind": "dc", "args": "Vin 1 2 1"},
                                   [{"name": "m", "spice": ".meas dc m "
                                    "FIND v(vout) AT=2"}], "/o")
        self.assertEqual(list(req),
                         ["netlist", "backend", "batch", "models", "analysis",
                          "measurements", "corners", "options"])
        self.assertEqual(list(req["options"]),
                         ["timeout_s", "keep_artifacts", "waveforms",
                          "stage_model_inputs", "osdi_preload"])
        self.assertEqual(req["batch"],
                         {"runner_version_check": "warn", "capacity_wait_s": 600})

    def test_probe_exclude_comes_last_and_full_matrix_has_none(self):
        full = re_.request_skeleton(re_.coords(probe=True), "analysis",
                                    {"kind": "op", "args": ""}, [], "/o")
        self.assertEqual(list(full)[-1], "exclude")
        self.assertEqual(len(full["exclude"]), 2)
        none = re_.request_skeleton(re_.coords(), "analysis",
                                    {"kind": "op", "args": ""}, [], "/o")
        self.assertNotIn("exclude", none)

    def test_row4_request_obj_is_the_skeleton_with_row4_halves(self):
        self.assertEqual(r4.request_obj("/o", re_.coords()),
                         re_.request_skeleton(re_.coords(), "analysis",
                                              {"kind": "dc", "args": r4.VIN_AXIS},
                                              r4.measurements(), "/o"))

    def test_row7_request_obj_is_the_skeleton_with_row7_halves(self):
        self.assertEqual(
            r7.request_obj("/o", re_.coords()),
            re_.request_skeleton(
                re_.coords(), "analysis_steps", r7.analysis_steps(),
                r7.measurements(), "/o",
                extra_options={"ngspice_options": dict(r7.NGSPICE_OPTIONS),
                               "ngspice_init": list(r7.NGSPICE_INIT)},
                timeout_s=600))


class GateChecks(unittest.TestCase):
    """The shared declared-gate check catches a dropped tag or relaxed limit
    in a committed record's request, for either driver's shape."""

    def record_dir(self, driver):
        tmp = tempfile.mkdtemp(prefix="row-envelope-gate-test.")
        self.addCleanup(shutil.rmtree, tmp, True)
        files = driver.request_files(SUBS, re_.coords(), TMPL)
        for name, text in files.items():
            with open(os.path.join(tmp, name), "w") as f:
                f.write(text)
        with open(os.path.join(tmp, "report.json"), "w") as f:
            json.dump({"provenance": {"input": {}}, "netlist": "tb.spice",
                       "environment": {}, "measurements": [], "corners": []}, f)
        return tmp

    def test_relaxed_limit_in_the_request_is_caught(self):
        for driver, slug in ((r4, "row4"), (r7, "row7")):
            with self.subTest(driver=slug):
                tmp = self.record_dir(driver)
                path = os.path.join(tmp, "request.json")
                req = json.load(open(path))
                for m in req["measurements"]:
                    if m.get("limits"):
                        m["limits"] = {"max": 9.0}
                json.dump(req, open(path, "w"), indent=1)
                problems = []
                re_.check_declared_gates(tmp, "rid", problems,
                                         measurements_fn=driver.measurements,
                                         graded=driver.GRADED,
                                         row_id=(r4.ROW4_ID if slug == "row4"
                                                 else r7.ROW7_ID),
                                         slug=slug)
                self.assertTrue(any("limits" in p for p in problems), problems)

    def test_dropped_spec_row_tag_is_caught(self):
        tmp = self.record_dir(r7)
        path = os.path.join(tmp, "request.json")
        req = json.load(open(path))
        req["measurements"][0].pop("spec_row")
        json.dump(req, open(path, "w"), indent=1)
        problems = []
        re_.check_declared_gates(tmp, "rid", problems,
                                 measurements_fn=r7.measurements,
                                 graded=r7.GRADED, row_id=r7.ROW7_ID, slug="row7")
        self.assertTrue(any("spec_row" in p for p in problems), problems)

    def test_ungraded_measurement_claiming_a_row_is_caught(self):
        # The step supply currents stay untagged; a tag smuggled onto one
        # would claim row coverage for a quantity that grades nothing.
        tmp = self.record_dir(r7)
        rep = json.load(open(os.path.join(tmp, "report.json")))
        rep["measurements"] = [
            {"name": "v3v30_i0.isup_a", "limits": None, "spec_row": r7.ROW7_ID}]
        json.dump(rep, open(os.path.join(tmp, "report.json"), "w"))
        problems = []
        re_.check_declared_gates(tmp, "rid", problems,
                                 measurements_fn=r7.measurements,
                                 graded=r7.GRADED, row_id=r7.ROW7_ID, slug="row7")
        self.assertTrue(any("claims spec_row" in p for p in problems), problems)

    def test_echoed_options_gate(self):
        tmp = self.record_dir(r7)
        req = json.load(open(os.path.join(tmp, "request.json")))
        asked = (req.get("options") or {}).get("ngspice_options")
        self.assertIsNotNone(asked)
        rpath = os.path.join(tmp, "report.json")
        rep = json.load(open(rpath))

        rep["environment"] = {"ngspice_options": dict(asked)}
        json.dump(rep, open(rpath, "w"))
        problems = []
        re_.check_echoed_options(tmp, "rid", problems)
        self.assertEqual(problems, [])

        rep["environment"] = {"ngspice_options": {"reltol": 0.5}}
        json.dump(rep, open(rpath, "w"))
        problems = []
        re_.check_echoed_options(tmp, "rid", problems)
        self.assertEqual(len(problems), 1, problems)
        self.assertIn("ngspice_options", problems[0])

        open(rpath, "w").write("{not json")
        problems = []
        re_.check_echoed_options(tmp, "rid", problems)
        self.assertTrue(any("cannot compare" in p for p in problems), problems)
        os.remove(rpath)
        problems = []
        re_.check_echoed_options(tmp, "rid", problems)
        self.assertTrue(any("cannot compare" in p for p in problems), problems)

    def test_summarise_corners_empty_report_is_never_definitive(self):
        summ, points, base = re_.summarise_corners(
            {"corners": []}, {"record_id": "x"}, graded=["a"])
        self.assertEqual(points, [])
        self.assertFalse(base)
        self.assertNotIn("all_graded_strictly_below_target", summ)
        summ, _, base = re_.summarise_corners(
            {"corners": []}, {"record_id": "x"}, graded=["a"],
            step_names=["s"], target_of=lambda n: 1.0)
        self.assertFalse(base)
        self.assertIn("graded_declarations_exactly_once", summ)

    def test_selected_record_reads_the_repo_it_is_given(self):
        tmp = tempfile.mkdtemp(prefix="row-envelope-sel-test.")
        self.addCleanup(shutil.rmtree, tmp, True)
        os.makedirs(os.path.join(tmp, "sim", "characterization"))
        json.dump({"k": {"id": "R1"}}, open(
            os.path.join(tmp, "sim", "characterization", "selection.json"), "w"))
        self.assertEqual(re_.selected_record(tmp, "k"), "R1")
        self.assertIsNone(re_.selected_record(tmp, "other"))
        problems = []
        re_.check_selected_record(tmp, "k", "row-x", {}, problems, lambda r: [])
        self.assertEqual(len(problems), 1)
        problems = []
        re_.check_selected_record(tmp, "other", "row-x", {}, problems,
                                 lambda r: [], allow_none=True)
        self.assertEqual(problems, [])


class Item5CitationHelpers(unittest.TestCase):
    """The shared signoff item-5 resolver and its enforcement (#358).

    Row-agnostic by contract: repo/root/row_id/slug are call-time
    parameters (the stale_inputs() pattern), which is what lets the
    drivers' unit tests rebind their own REPO/ROOT globals. All fixtures
    here are synthetic; no committed record is read. The drivers' own
    ManifestCoupling/SignoffItem5Coupling classes carry the committed-tree
    negative controls; this class pins the shared machinery itself,
    including the refusals a committed tree cannot produce on demand
    (a probe summary that claims definitive, an unreadable provenance).
    """

    ROW = "dr0007-row9-test"
    SLUG = "row9"

    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix="row-envelope-item5-test.")
        self.addCleanup(shutil.rmtree, self.tmp, True)
        self.repo = self.tmp
        self.root = os.path.join(self.repo, "sim", "x", "row9-envelope")
        self.rid = "20260101-000000-test"
        rec = os.path.join(self.root, self.rid)
        os.makedirs(rec)
        with open(os.path.join(rec, "tb.spice"), "w") as f:
            f.write("* netlist\n")
        with open(os.path.join(rec, "provenance.json"), "w") as f:
            json.dump({"record_id": self.rid, "solver_profile": "standard"}, f)
        os.makedirs(os.path.join(self.repo, "signoff"))
        self.write_manifest({"evidence": {"5": []}})

    def write_manifest(self, doc):
        with open(os.path.join(self.repo, "signoff", "sg13g2-ldo.json"), "w") as f:
            json.dump(doc, f)

    def member(self, **kw):
        ent = {"file": f"sim/x/row9-envelope/{self.rid}/report.json",
               "content_hash": "sha256:" + re_.sha256_file(
                   os.path.join(self.root, self.rid, "tb.spice")),
               "rows": [self.ROW]}
        ent.update(kw)
        return ent

    def cite(self, *members):
        self.write_manifest({"evidence": {"5": list(members)}})

    def summaries(self, **over):
        summ = {"probe": False, "definitive": True}
        summ.update(over)
        return {self.rid: summ}

    def check(self, summaries=None, stale=None, **kw):
        problems = []
        cited = re_.check_item5_citation(
            self.repo, self.root, self.ROW, self.SLUG,
            self.summaries() if summaries is None else summaries,
            problems, stale or (lambda rid: []), **kw)
        return cited, problems

    def resolve(self):
        return re_.cited_item5_record(self.repo, self.root, self.ROW, self.SLUG)

    def test_uncited_item5_resolves_to_nothing_and_checks_clean(self):
        self.cite()
        self.assertEqual(self.resolve(), (None, None))
        self.assertEqual(self.check(), (None, []))

    def test_a_well_formed_member_resolves_and_checks_clean(self):
        self.cite(self.member())
        rid, pinned = self.resolve()
        self.assertEqual(rid, self.rid)
        self.assertEqual(pinned, self.member()["content_hash"])
        self.assertEqual(self.check(), (self.rid, []))

    def test_more_than_one_driver_member_is_an_error(self):
        self.cite(self.member(), self.member())
        with self.assertRaises(re_.Error) as cm:
            self.resolve()
        self.assertIn("exactly one", str(cm.exception))
        cited, problems = self.check()
        self.assertIsNone(cited)
        self.assertTrue(any("exactly one" in p for p in problems), problems)

    def test_foreign_or_missing_rows_is_an_error(self):
        no_rows = {k: v for k, v in self.member().items() if k != "rows"}
        for member in (self.member(rows=["dr0007-row4-dropout"]), no_rows):
            with self.subTest(member=member):
                self.cite(member)
                with self.assertRaises(re_.Error) as cm:
                    self.resolve()
                self.assertIn("declares rows", str(cm.exception))
                cited, problems = self.check()
                self.assertIsNone(cited)
                self.assertTrue(any("declares rows" in p for p in problems), problems)

    def test_wrong_file_shape_is_an_error(self):
        for file in (f"sim/x/row9-envelope/{self.rid}/request.json",
                     f"sim/x/row9-envelope/{self.rid}/sub/report.json",
                     "sim/x/row9-envelope/report.json"):
            with self.subTest(file=file):
                self.cite(self.member(file=file))
                with self.assertRaises(re_.Error) as cm:
                    self.resolve()
                self.assertIn("must be", str(cm.exception))

    def test_a_record_missing_from_summaries_is_not_committed(self):
        self.cite(self.member(file=f"sim/x/row9-envelope/elsewhere/report.json",
                              content_hash="sha256:" + "0" * 64))
        cited, problems = self.check()
        self.assertTrue(any("not committed" in p for p in problems), problems)

    def test_a_content_hash_that_is_not_the_tb_spice_is_refused(self):
        # The issue's evidence: pinning the sha256 of report.json (or any
        # other file) instead of tb.spice must fail here, offline.
        wrong = "sha256:" + re_.sha256_file(os.path.join(self.root, self.rid,
                                                         "provenance.json"))
        self.cite(self.member(content_hash=wrong))
        cited, problems = self.check()
        self.assertEqual(cited, self.rid)
        self.assertTrue(any("content_hash" in p for p in problems), problems)

    def test_a_non_definitive_summary_is_refused(self):
        self.cite(self.member())
        cited, problems = self.check(summaries=self.summaries(definitive=False))
        self.assertTrue(any("not definitive" in p for p in problems), problems)

    def test_a_summary_without_a_verdict_is_refused(self):
        self.cite(self.member())
        cited, problems = self.check(summaries={self.rid: None})
        self.assertTrue(any("not definitive" in p for p in problems), problems)

    def test_a_probe_summary_is_refused(self):
        # A committed probe never reaches this branch with definitive=True;
        # the refusal exists for exactly that lying shape.
        self.cite(self.member())
        cited, problems = self.check(summaries=self.summaries(probe=True))
        self.assertTrue(any("probe record" in p for p in problems), problems)

    def test_stale_inputs_on_the_cited_record_are_reported(self):
        self.cite(self.member())
        cited, problems = self.check(stale=lambda rid: [f"cited record {rid}: stale"])
        self.assertTrue(any("stale" in p for p in problems), problems)

    def test_a_non_standard_solver_profile_is_refused_only_when_required(self):
        with open(os.path.join(self.root, self.rid, "provenance.json"), "w") as f:
            json.dump({"record_id": self.rid, "solver_profile": "tight-1e-10"}, f)
        self.cite(self.member())
        # row 5's shape: no profile requirement, no problem
        self.assertEqual(self.check()[1], [])
        # row 7's shape: the byte-identical tight pair must be refused
        cited, problems = self.check(require_standard_solver_profile=True)
        self.assertEqual(cited, self.rid)
        self.assertTrue(any("solver_profile" in p for p in problems), problems)

    def test_an_unreadable_solver_profile_refuses_rather_than_crashes(self):
        os.remove(os.path.join(self.root, self.rid, "provenance.json"))
        self.cite(self.member())
        cited, problems = self.check(require_standard_solver_profile=True)
        self.assertTrue(any("solver profile" in p for p in problems), problems)

    def test_the_drivers_wrap_the_shared_resolver_with_their_own_identity(self):
        # Each driver's cited_record() is its row id + record directory
        # around the one parser; the row-4 delegation (#358) must resolve
        # the committed manifest exactly as the row4-local parser did.
        self.assertEqual(r4.cited_record(),
                         re_.cited_item5_record(r4.REPO, r4.ROOT, r4.ROW4_ID, "row4"))
        self.assertEqual(r5.cited_record(),
                         re_.cited_item5_record(r5.REPO, r5.ROOT, r5.ROW5_ID, "row5"))
        self.assertEqual(r7.cited_record(),
                         re_.cited_item5_record(r7.REPO, r7.ROOT, r7.ROW7_ID, "row7"))




